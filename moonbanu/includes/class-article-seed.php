	/** متای مقاله که نشان می‌دهد بازبینی تخصصی انجام شده است. */
	const REVIEWED_META = 'mb_reviewed_by';

	public static function init(): void {
		add_action( 'init', array( __CLASS__, 'maybe_seed' ), 40 );
	}

	/** آیا این مقاله بازبینی تخصصی واقعی دارد؟ */
	public static function is_reviewed( int $post_id ): bool {
		return '' !== trim( (string) get_post_meta( $post_id, self::REVIEWED_META, true ) );
	}

	/** برچسب پایین هر مقاله. */
	public static function badge( int $post_id ): string {
		if ( self::is_reviewed( $post_id ) ) {
			return 'بازبینی تخصصی: ' . sanitize_text_field( (string) get_post_meta( $post_id, self::REVIEWED_META, true ) );
		}
		return self::LABEL;
	}

	/* --------------------------------------------------------------------- */
	/* seed                                                                  */
	/* --------------------------------------------------------------------- */

	public static function maybe_seed(): void {
		if ( get_option( 'mb_articles_seeded' ) ) {
			return;
		}

		foreach ( self::defaults() as $item ) {
			$exists = get_posts(
				array(
					'post_type'      => 'mb_article',
					'title'          => $item['title'],
					'posts_per_page' => 1,
					'fields'         => 'ids',
					'post_status'    => 'any',
				)
			);
			if ( ! empty( $exists ) ) {
				continue;
			}

			$id = wp_insert_post(
				array(
					'post_type'    => 'mb_article',
					'post_status'  => 'publish',
					'post_title'   => $item['title'],
					'post_excerpt' => $item['excerpt'],
					'post_content' => $item['body'] . self::sources_block( $item['sources'] ),
				),
				true
			);
			if ( is_wp_error( $id ) ) {
				continue;
			}

			update_post_meta( (int) $id, 'read_minutes', (int) $item['minutes'] );
			$term = term_exists( $item['cat'], 'mb_cat' );
			if ( $term ) {
				wp_set_object_terms( (int) $id, (int) ( is_array( $term ) ? $term['term_id'] : $term ), 'mb_cat' );
			}
		}

		update_option( 'mb_articles_seeded', 1 );
	}

	private static function sources_block( array $sources ): string {
		$items = '';
		foreach ( $sources as $source ) {
			$items .= '<li>' . esc_html( $source ) . '</li>';
		}
		return '<h3>منابع</h3><ul>' . $items . '</ul>'
			. '<p class="disclaimer">' . esc_html( self::LABEL ) . '</p>';
	}

