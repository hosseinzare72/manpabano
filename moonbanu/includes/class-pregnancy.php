	/**
	 * تنها دو فیلد مجاز برای همسر. هیچ داده‌ای جز شمارهٔ هفته و تاریخ موعد
	 * از این متد بیرون نمی‌آید.
	 *
	 * @return array{pregnancy_week:int,due_date:string}|array{}
	 */
	public static function partner_fields( int $wife_id ): array {
		$row = MB_DB::get_active_pregnancy( $wife_id );
		if ( ! $row || empty( $row['share_pregnancy'] ) ) {
			return array();
		}
		$days = max( 0, MB_Jalali::diff_days( (string) $row['lmp_date'], MB_Jalali::today() ) );
		return array(
			'pregnancy_week' => self::week_from_days( $days ),
			'due_date'       => MB_Jalali::format_fa( (string) $row['due_date'], 'long' ),
		);
	}
