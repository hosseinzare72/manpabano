	public static function week_card( int $week ): array {
		$week    = (int) max( 1, min( 42, $week ) );
		$content = self::weeks();
		if ( isset( $content[ $week ] ) ) {
			$card = $content[ $week ];
		} else {
			$card = $content[40];
		}
		$card['week']      = $week;
		$card['trimester'] = self::trimester( $week );
		$card['trimester_label'] = self::trimester_label( self::trimester( $week ) );
		return $card;
	}

