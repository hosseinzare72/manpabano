	/** طول بارداری بر پایهٔ قاعدهٔ ناگل. */
	const GESTATION_DAYS = 280;

	/* --------------------------------------------------------------------- */
	/* وضعیت                                                                 */
	/* --------------------------------------------------------------------- */

	public static function is_active( int $user_id ): bool {
		return null !== MB_DB::get_active_pregnancy( $user_id );
	}

	public static function get( int $user_id ): ?array {
		$row = MB_DB::get_active_pregnancy( $user_id );
		if ( ! $row ) {
			return null;
		}
		$today = MB_Jalali::today();
		$days  = MB_Jalali::diff_days( (string) $row['lmp_date'], $today );
		$days  = max( 0, $days );
		$week  = self::week_from_days( $days );

		$row['days']          = $days;
		$row['week']          = $week;
		$row['day_of_week']   = ( $days % 7 ) + 1;
		$row['trimester']     = self::trimester( $week );
		$row['days_left']     = MB_Jalali::diff_days( $today, (string) $row['due_date'] );
		$row['progress']      = (int) max( 0, min( 100, round( ( $days / self::GESTATION_DAYS ) * 100 ) ) );
		$row['lmp_jalali']    = MB_Jalali::format_fa( (string) $row['lmp_date'], 'long' );
		$row['due_jalali']    = MB_Jalali::format_fa( (string) $row['due_date'], 'long' );
		$row['card']          = self::week_card( $week );
		$row['share']         = (int) ( $row['share_pregnancy'] ?? 0 );
		return $row;
	}

	/** هفتهٔ بارداری = floor(روزها / ۷) + ۱، محدود به ۱..۴۲. */
	public static function week_from_days( int $days ): int {
		return (int) max( 1, min( 42, intdiv( max( 0, $days ), 7 ) + 1 ) );
	}

	public static function trimester( int $week ): int {
		if ( $week <= 13 ) {
			return 1;
		}
		return $week <= 27 ? 2 : 3;
	}

	public static function trimester_label( int $trimester ): string {
		$map = array( 1 => 'سه‌ماههٔ اول', 2 => 'سه‌ماههٔ دوم', 3 => 'سه‌ماههٔ سوم' );
		return $map[ $trimester ] ?? '';
	}

	/** تاریخ تقریبی زایمان از LMP. */
	public static function due_from_lmp( string $lmp ): string {
		return MB_Jalali::add_days( MB_Jalali::sanitize_date( $lmp ), self::GESTATION_DAYS );
	}

