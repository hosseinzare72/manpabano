	/**
	 * شروع حالت بارداری. LMP نباید در آینده یا بیش از ۳۰۰ روز پیش باشد.
	 *
	 * @return array{ok:bool,message:string,due?:string}
	 */
	public static function start( int $user_id, string $lmp ): array {
		// MB_Jalali::sanitize_date() برای هر ورودی نامعتبر «امروز» برمی‌گرداند،
		// پس بررسی اعتبار باید پیش از آن انجام شود؛ وگرنه تاریخ بی‌معنی به
		// بارداریِ آغازشده در امروز تبدیل می‌شد.
		$lmp = trim( MB_Jalali::en_num( $lmp ) );
		if ( '' === $lmp || ! MB_Jalali::is_valid( $lmp ) ) {
			return array( 'ok' => false, 'message' => 'تاریخ آخرین قاعدگی درست نیست.' );
		}
		$lmp = MB_Jalali::sanitize_date( $lmp );
		$today = MB_Jalali::today();
		$days  = MB_Jalali::diff_days( $lmp, $today );
		if ( $days < 0 ) {
			return array( 'ok' => false, 'message' => 'تاریخ آخرین قاعدگی نمی‌تواند در آینده باشد.' );
		}
		if ( $days > 300 ) {
			return array( 'ok' => false, 'message' => 'این تاریخ برای شروع حالت بارداری خیلی قدیمی است.' );
		}

		$due = self::due_from_lmp( $lmp );
		MB_DB::start_pregnancy( $user_id, $lmp, $due );
		MB_DB::add_notification( $user_id, 'pregnancy_start', array( 'due' => MB_Jalali::format_fa( $due, 'long' ) ) );

		return array(
			'ok'      => true,
			'message' => 'حالت بارداری فعال شد.',
			'due'     => $due,
		);
	}

	public static function stop( int $user_id ): array {
		MB_DB::end_pregnancy( $user_id );
		return array( 'ok' => true, 'message' => 'حالت بارداری خاموش شد. پیش‌بینی چرخه دوباره فعال می‌شود.' );
	}

