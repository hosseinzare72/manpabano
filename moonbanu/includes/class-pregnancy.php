	public static function get_checklist( int $user_id ): array {
		$saved = get_user_meta( $user_id, 'mb_pregnancy_checklist', true );
		$saved = is_array( $saved ) ? $saved : array();
		$out   = array();
		foreach ( self::checklist_items() as $key => $item ) {
			$out[ $key ] = array(
				'label' => $item['label'],
				'week'  => (int) $item['week'],
				'done'  => ! empty( $saved[ $key ] ),
			);
		}
		return $out;
	}

	public static function toggle_checklist( int $user_id, string $key, bool $done ): bool {
		$key = sanitize_key( $key );
		if ( ! array_key_exists( $key, self::checklist_items() ) ) {
			return false;
		}
		$saved = get_user_meta( $user_id, 'mb_pregnancy_checklist', true );
		$saved = is_array( $saved ) ? $saved : array();
		if ( $done ) {
			$saved[ $key ] = 1;
		} else {
			unset( $saved[ $key ] );
		}
		update_user_meta( $user_id, 'mb_pregnancy_checklist', $saved );
		return true;
	}

