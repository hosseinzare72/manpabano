	public static function maybe_seed(): void {
		if ( get_option( 'mb_faq_seeded' ) ) {
			return;
		}
		$order = 0;
		foreach ( self::defaults() as $item ) {
			++$order;
			$exists = get_posts(
				array(
					'post_type'      => self::CPT,
					'title'          => $item['q'],
					'posts_per_page' => 1,
					'fields'         => 'ids',
					'post_status'    => 'any',
				)
			);
			if ( ! empty( $exists ) ) {
				continue;
			}
			$id = wp_insert_post(
				array(
					'post_type'    => self::CPT,
					'post_status'  => 'publish',
					'post_title'   => $item['q'],
					'post_content' => $item['a'],
					'menu_order'   => $order,
				),
				true
			);
			if ( ! is_wp_error( $id ) ) {
				update_post_meta( (int) $id, 'cat', $item['cat'] );
				update_post_meta( (int) $id, 'published', 1 );
			}
		}
		update_option( 'mb_faq_seeded', 1 );
	}

