	/**
	 * فهرست پرسش‌ها، گروه‌بندی‌شده بر اساس دسته.
	 *
	 * @param string $search جست‌وجو در متن پرسش و پاسخ.
	 * @return array<string,array{label:string,items:array}>
	 */
	public static function grouped( string $search = '' ): array {
		$args = array(
			'post_type'      => self::CPT,
			'post_status'    => 'publish',
			'posts_per_page' => 200,
			'orderby'        => array( 'menu_order' => 'ASC', 'ID' => 'ASC' ),
			'no_found_rows'  => true,
		);
		$search = trim( sanitize_text_field( $search ) );
		if ( '' !== $search ) {
			$args['s'] = $search;
		}

		$out = array();
		foreach ( self::categories() as $key => $label ) {
			$out[ $key ] = array( 'label' => $label, 'items' => array() );
		}

		$query = new WP_Query( $args );
		foreach ( $query->posts as $post ) {
			if ( ! $post instanceof WP_Post ) {
				continue;
			}
			if ( 0 === (int) get_post_meta( $post->ID, 'published', true ) ) {
				continue;
			}
			$cat = (string) get_post_meta( $post->ID, 'cat', true );
			if ( ! isset( $out[ $cat ] ) ) {
				$cat = 'cycle';
			}
			$out[ $cat ]['items'][] = array(
				'id'       => (int) $post->ID,
				'question' => (string) $post->post_title,
				'answer'   => wp_kses_post( wpautop( (string) $post->post_content ) ),
			);
		}
		wp_reset_postdata();

		// دستهٔ خالی نمایش داده نمی‌شود.
		foreach ( $out as $key => $group ) {
			if ( empty( $group['items'] ) ) {
				unset( $out[ $key ] );
			}
		}
		return $out;
	}

	public static function count(): int {
		$counts = wp_count_posts( self::CPT );
		return (int) ( $counts->publish ?? 0 );
	}

